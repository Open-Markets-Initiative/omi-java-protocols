package omi.siac.opra.output.obi.v6_3_a.enums;

import java.util.Optional;

/**
 * 0x00 for regular trading session
 *
 * <p>Backed by short. Values correspond to the wire integer encoding.</p>
 */
public enum SessionIndicator {

    /**
     * Regular Trading Session
     */
    REGULAR((short) 0, "Regular Trading Session"),

    /**
     * Global Trading Hours session: Sunday into Monday
     */
    SUNDAY_INTO_MONDAY((short) 1, "Global Trading Hours session: Sunday into Monday"),

    /**
     * Global Trading Hours session: Monday into Tuesday
     */
    MONDAY_INTO_TUESDAY((short) 2, "Global Trading Hours session: Monday into Tuesday"),

    /**
     * Global Trading Hours session: Tuesday into Wednesday
     */
    TUESDAY_INTO_WEDNESDAY((short) 3, "Global Trading Hours session: Tuesday into Wednesday"),

    /**
     * Global Trading Hours session: Wednesday into Thursday
     */
    WEDNESDAY_INTO_THURSDAY((short) 4, "Global Trading Hours session: Wednesday into Thursday"),

    /**
     * Global Trading Hours session: Thursday into Friday
     */
    THURSDAY_INTO_FRIDAY((short) 5, "Global Trading Hours session: Thursday into Friday"),

    /**
     * ASCII 'X' (hex 0x58) on any messages generated by OPRA during GTH, e.g. Control (Category H) messages or OPRA-generated Zero Quotes
     */
    GENERATED_BY_OPRA((short) 88, "ASCII 'X' (hex 0x58) on any messages generated by OPRA during GTH, e.g. Control (Category H) messages or OPRA-generated Zero Quotes");

    private final short wire;

    private final String description;

    SessionIndicator(short wire, String description) {
        this.wire = wire;
        this.description = description;
    }

    /**
     * Returns this value's encoding on the wire.
     *
     * @return the wire value
     */
    public short wire() {
        return wire;
    }

    /**
     * Returns the description the protocol specification gives this value.
     *
     * @return the description
     */
    public String description() {
        return description;
    }

    /**
     * Returns the value with the given wire encoding.
     *
     * @param wire the encoding read from the wire
     * @return the matching value, or empty when the protocol declares no value for it
     */
    public static Optional<SessionIndicator> fromWire(short wire) {
        return switch (wire) {
            case 0 -> Optional.of(REGULAR);
            case 1 -> Optional.of(SUNDAY_INTO_MONDAY);
            case 2 -> Optional.of(MONDAY_INTO_TUESDAY);
            case 3 -> Optional.of(TUESDAY_INTO_WEDNESDAY);
            case 4 -> Optional.of(WEDNESDAY_INTO_THURSDAY);
            case 5 -> Optional.of(THURSDAY_INTO_FRIDAY);
            case 88 -> Optional.of(GENERATED_BY_OPRA);
            default -> Optional.empty();
        };
    }
}
