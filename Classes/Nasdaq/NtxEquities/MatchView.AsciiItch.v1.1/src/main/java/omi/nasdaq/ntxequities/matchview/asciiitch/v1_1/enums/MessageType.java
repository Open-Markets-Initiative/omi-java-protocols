package omi.nasdaq.ntxequities.matchview.asciiitch.v1_1.enums;

import java.util.Optional;

/**
 * Code identifying this message type
 *
 * <p>Each value corresponds to the ASCII character used as the wire discriminator.</p>
 */
public enum MessageType {

    /**
     * The prevailing best bid and offer of the other exchanges as the Nasdaq Texas execution system sees it.
     */
    QUOTE_UPDATE_MESSAGE('U', "The prevailing best bid and offer of the other exchanges as the Nasdaq Texas execution system sees it.");

    private final char wire;

    private final String description;

    MessageType(char wire, String description) {
        this.wire = wire;
        this.description = description;
    }

    /**
     * Returns this value's encoding on the wire.
     *
     * @return the wire value
     */
    public char wire() {
        return wire;
    }

    /**
     * Returns the description the protocol specification gives this value.
     *
     * @return the description
     */
    public String description() {
        return description;
    }

    /**
     * Returns the value with the given wire encoding.
     *
     * @param wire the encoding read from the wire
     * @return the matching value, or empty when the protocol declares no value for it
     */
    public static Optional<MessageType> fromWire(char wire) {
        return wire == 'U' ? Optional.of(QUOTE_UPDATE_MESSAGE) : Optional.empty();
    }
}
