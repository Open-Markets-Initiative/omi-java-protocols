    public int encode(byte[] data, int offset) {
        Objects.checkFromIndexSize(offset, BYTE_LENGTH, data.length);
        int cursor = offset;
        cursor = sourceTime.encode(data, cursor);
        cursor = sourceTimeNs.encode(data, cursor);
        cursor = symbolIndex.encode(data, cursor);
        cursor = symbolSeqNumber.encode(data, cursor);
        cursor = tradeId.encode(data, cursor);
        cursor = price.encode(data, cursor);
        cursor = volume.encode(data, cursor);
        cursor = tradeCondition1.encode(data, cursor);
        cursor = tradeCondition2.encode(data, cursor);
        cursor = tradeCondition3.encode(data, cursor);
        cursor = tradeCondition4.encode(data, cursor);
        cursor = marketId.encode(data, cursor);
        return cursor;
    }

