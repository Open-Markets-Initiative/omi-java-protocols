    @Override
    public boolean parseFrom(byte[] data, int offset, int end) {
        clear();
        this.decoded = read(data, offset, end);

        int stop = Math.max(0, Math.min(data.length, offset + BYTE_LENGTH));
        this.buffer = Arrays.copyOfRange(data, Math.min(Math.max(offset, 0), stop), stop);
        return decoded;
    }

    private boolean read(byte[] data, int offset, int end) {
        if (offset < 0 || end > data.length || end - offset < BYTE_LENGTH) {
            return false;
        }

        int cursor = offset;
        if (!sourceTime.parse(data, cursor)) {
            return false;
        }
        cursor += SourceTimeField.BYTE_LENGTH;
        if (!sourceTimeNs.parse(data, cursor)) {
            return false;
        }
        cursor += SourceTimeNsField.BYTE_LENGTH;
        if (!symbolIndex.parse(data, cursor)) {
            return false;
        }
        cursor += SymbolIndexField.BYTE_LENGTH;
        if (!symbolSeqNumber.parse(data, cursor)) {
            return false;
        }
        cursor += SymbolSeqNumberField.BYTE_LENGTH;
        if (!tradeId.parse(data, cursor)) {
            return false;
        }
        cursor += TradeIdField.BYTE_LENGTH;
        if (!price.parse(data, cursor)) {
            return false;
        }
        cursor += PriceField.BYTE_LENGTH;
        if (!volume.parse(data, cursor)) {
            return false;
        }
        cursor += VolumeField.BYTE_LENGTH;
        if (!tradeCondition1.parse(data, cursor)) {
            return false;
        }
        cursor += TradeCondition1Field.BYTE_LENGTH;
        if (!tradeCondition2.parse(data, cursor)) {
            return false;
        }
        cursor += TradeCondition2Field.BYTE_LENGTH;
        if (!tradeCondition3.parse(data, cursor)) {
            return false;
        }
        cursor += TradeCondition3Field.BYTE_LENGTH;
        if (!tradeCondition4.parse(data, cursor)) {
            return false;
        }
        cursor += TradeCondition4Field.BYTE_LENGTH;
        return marketId.parse(data, cursor);
    }

