package omi.miax.pearlequities.expressorders.meo.v2_6.messages.application;

import java.time.Instant;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.IntStream;
import omi.miax.pearlequities.expressorders.meo.v2_6.fields.ClientOrderIdField;
import omi.miax.pearlequities.expressorders.meo.v2_6.fields.MpidField;
import omi.miax.pearlequities.expressorders.meo.v2_6.fields.NotificationTimeField;
import omi.miax.pearlequities.expressorders.meo.v2_6.fields.NumberOfMatchingEnginesField;
import omi.miax.pearlequities.expressorders.meo.v2_6.groups.MatchingEngineEntry;
import omi.miax.pearlequities.expressorders.meo.v2_6.groups.MatchingEngineList;
import omi.miax.pearlequities.expressorders.meo.v2_6.types.Field;
import omi.miax.pearlequities.expressorders.meo.v2_6.types.Message;
import omi.miax.pearlequities.expressorders.meo.v2_6.types.PrintOptions;

/**
 * Represents the MassCancelResponse message from the ExpressOrders protocol.
 *
 * <p>This message format will be used to inform the Firm about the status of their previous Mass Cancel Request</p>
 */
public final class MassCancelResponse implements Message {

    /**
     * This message's width on the wire with every counted repeating group empty.
     */
    public static final int MINIMUM_BYTE_LENGTH = 43;

    /**
     * This message's declared name.
     */
    public static final String NAME = "Mass Cancel Response";

    /**
     * Time at which this message was generated by the
     */
    private final NotificationTimeField notificationTime = new NotificationTimeField();

    /**
     * Four character NSCC MPID of the Firm
     */
    private final MpidField mpid = new MpidField();

    /**
     * Firm specified unique order Id
     */
    private final ClientOrderIdField clientOrderId = new ClientOrderIdField();

    /**
     * 24 This is the number of Matching Engines in
     */
    private final NumberOfMatchingEnginesField numberOfMatchingEngines = new NumberOfMatchingEnginesField();

    /**
     * Status response for the Mass Cancel Request from each Matching Engine, in sequential order
     */
    private final MatchingEngineList matchingEngine = new MatchingEngineList();

    /**
     * This message's fields, in wire order.
     */
    private final List<Field> fields = List.of(notificationTime, mpid, clientOrderId, numberOfMatchingEngines);

    private byte[] buffer;

    private boolean decoded;

    private int gapOffset0 = -1;

    /**
     * Time at which this message was generated by the
     *
     * @return the NotificationTime field
     */
    public NotificationTimeField notificationTime() {
        return notificationTime;
    }

    /**
     * Four character NSCC MPID of the Firm
     *
     * @return the Mpid field
     */
    public MpidField mpid() {
        return mpid;
    }

    /**
     * Firm specified unique order Id
     *
     * @return the ClientOrderId field
     */
    public ClientOrderIdField clientOrderId() {
        return clientOrderId;
    }

    /**
     * 24 This is the number of Matching Engines in
     *
     * @return the NumberOfMatchingEngines field
     */
    public NumberOfMatchingEnginesField numberOfMatchingEngines() {
        return numberOfMatchingEngines;
    }

    /**
     * Status response for the Mass Cancel Request from each Matching Engine, in sequential order
     *
     * <p>Encode writes this list's size to the NumberOfMatchingEngines field.</p>
     *
     * @return the MatchingEngine entries
     */
    public MatchingEngineList matchingEngine() {
        return matchingEngine;
    }

    @Override
    public Optional<Character> type() {
        return Optional.empty();
    }

    @Override
    public int byteLength() {
        return MINIMUM_BYTE_LENGTH + matchingEngine.byteLength();
    }

    /**
     * Returns this message's declared padding runs, as consecutive offset and length pairs relative to the start of the message, for the entries it holds now.
     *
     * <p>Padding carries no value: decode advances over it, and encode writes back what decode received, or zero for a message assembled from values. Use this to check a received message's padding where the specification constrains it, or to render a byte map of the layout.</p>
     *
     * @return the padding runs, empty when the layout has none
     */
    public int[] padding() {
        IntStream.Builder runs = IntStream.builder();
        padding(runs, 0);
        return runs.build().toArray();
    }

    /**
     * Adds the declared padding runs, as offset and length pairs.
     *
     * @param runs   the destination
     * @param offset the offset of this class's first byte, relative to the start of the message
     * @return the offset just past this class's last byte
     */
    public int padding(IntStream.Builder runs, int offset) {
        int cursor = offset;
        cursor += 8;
        cursor += 4;
        cursor += 20;
        cursor += 1;
        cursor += matchingEngine.byteLength();
        runs.add(cursor).add(10);
        cursor += 10;
        return cursor;
    }

    @Override
    public Optional<Instant> timestamp() {
        return Optional.ofNullable(notificationTime.value());
    }

    @Override
    public boolean parseFrom(byte[] data, int offset) {
        return parseFrom(data, offset, data.length);
    }

    @Override
    public boolean parseFrom(byte[] data, int offset, int end) {
        clear();
        this.decoded = read(data, offset, end);

        int stop = Math.max(0, Math.min(data.length, offset + byteLength()));
        this.buffer = Arrays.copyOfRange(data, Math.min(Math.max(offset, 0), stop), stop);
        return decoded;
    }

    private boolean read(byte[] data, int offset, int end) {
        if (offset < 0 || end > data.length || end - offset < MINIMUM_BYTE_LENGTH) {
            return false;
        }

        int cursor = offset;
        if (!notificationTime.parse(data, cursor)) {
            return false;
        }
        cursor += NotificationTimeField.BYTE_LENGTH;
        if (!mpid.parse(data, cursor)) {
            return false;
        }
        cursor += MpidField.BYTE_LENGTH;
        if (!clientOrderId.parse(data, cursor)) {
            return false;
        }
        cursor += ClientOrderIdField.BYTE_LENGTH;
        if (!numberOfMatchingEngines.parse(data, cursor)) {
            return false;
        }
        cursor += NumberOfMatchingEnginesField.BYTE_LENGTH;
        if (!matchingEngine.parse(data, cursor, end - 10, numberOfMatchingEngines.value())) {
            return false;
        }
        cursor += matchingEngine.byteLength();
        if (end - cursor < 10) {
            return false;
        }
        this.gapOffset0 = cursor - offset;

        return true;
    }

    @Override
    public int encode(byte[] data, int offset) {
        Objects.checkFromIndexSize(offset, byteLength(), data.length);
        if (matchingEngine.size() > 255) {
            throw new IllegalStateException("matchingEngine holds " + matchingEngine.size() + " entries, more than its count field can state");
        }
        numberOfMatchingEngines.value((short) matchingEngine.size());
        int cursor = offset;
        cursor = notificationTime.encode(data, cursor);
        cursor = mpid.encode(data, cursor);
        cursor = clientOrderId.encode(data, cursor);
        cursor = numberOfMatchingEngines.encode(data, cursor);
        cursor = matchingEngine.encode(data, cursor);
        if (buffer != null && gapOffset0 >= 0 && buffer.length >= gapOffset0 + 10) {
            System.arraycopy(buffer, gapOffset0, data, cursor, 10); // padding
        } else {
            Arrays.fill(data, cursor, cursor + 10, (byte) 0); // padding
        }
        cursor += 10;
        return cursor;
    }

    @Override
    public byte[] toBytes() {
        byte[] data = new byte[byteLength()];
        encode(data, 0);
        return data;
    }

    @Override
    public void clear() {
        for (Field field : fields) {
            field.reset();
        }
        matchingEngine.clear();
        this.gapOffset0 = -1;
        this.buffer = null;
        this.decoded = false;
    }

    @Override
    public boolean isDecoded() {
        return decoded;
    }

    @Override
    public boolean isRecognized() {
        if (buffer != null && !decoded) {
            return false;
        }
        for (Field field : fields) {
            if (field != numberOfMatchingEngines && !field.isRecognized()) {
                return false;
            }
        }
        return matchingEngine.isRecognized();
    }

    @Override
    public boolean isValid() {
        if (buffer != null && !decoded) {
            return false;
        }
        for (Field field : fields) {
            if (field != numberOfMatchingEngines && !field.isValid()) {
                return false;
            }
        }
        if (!matchingEngine.isValid()) {
            return false;
        }
        return isRecognized();
    }

    /**
     * Returns a copy of the bytes this message was decoded from.
     *
     * <p>A failed decode leaves behind the partial range that was available, which is what a diagnostic needs to see.</p>
     *
     * @return the message bytes, or empty when no decode has been attempted
     */
    @Override
    public Optional<byte[]> raw() {
        if (buffer == null) {
            return Optional.empty();
        }
        return Optional.of(buffer.clone());
    }

    @Override
    public Optional<Field> failedAt() {
        if (buffer == null || decoded) {
            return Optional.empty();
        }
        if (!notificationTime.isDecoded()) {
            return Optional.of(notificationTime);
        }
        if (!mpid.isDecoded()) {
            return Optional.of(mpid);
        }
        if (!clientOrderId.isDecoded()) {
            return Optional.of(clientOrderId);
        }
        if (!numberOfMatchingEngines.isDecoded()) {
            return Optional.of(numberOfMatchingEngines);
        }
        if (!matchingEngine.isDecoded()) {
            return Optional.of(matchingEngine.failedEntry().flatMap(MatchingEngineEntry::failedAt).orElse(numberOfMatchingEngines));
        }
        return Optional.empty();
    }

    @Override
    public List<Field> fields() {
        return fields;
    }

    @Override
    public Optional<Field> field(String name) {
        return switch (name) {
            case "NotificationTime" -> Optional.of(notificationTime);
            case "Mpid" -> Optional.of(mpid);
            case "ClientOrderId" -> Optional.of(clientOrderId);
            case "NumberOfMatchingEngines" -> Optional.of(numberOfMatchingEngines);
            default -> Optional.empty();
        };
    }

    @Override
    public List<Field> diffFields(Message other) {
        if (!(other instanceof MassCancelResponse message)) {
            return List.of();
        }
        List<Field> changed = new ArrayList<>();
        for (int index = 0; index < fields.size(); index++) {
            if (!fields.get(index).equals(message.fields.get(index))) {
                changed.add(fields.get(index));
            }
        }
        changed.addAll(matchingEngine.diffFields(message.matchingEngine));
        return changed;
    }

    @Override
    public String toFormattedString(PrintOptions options) {
        StringBuilder builder = new StringBuilder();
        toFormattedString(builder, options);
        return builder.toString();
    }

    /**
     * Appends this message's formatted representation.
     *
     * <p>The identifier form renders the message name alone, which is what a debugger label or a log line tracking message flow needs. The compact form adds every field on the same line, and the default form indents one field per line. Repeating groups follow the fields.</p>
     *
     * @param builder the destination
     * @param options the display options
     */
    @Override
    public void toFormattedString(StringBuilder builder, PrintOptions options) {
        if (options.identifier()) {
            builder.append(NAME);
            return;
        }

        if (options.compact()) {
            builder.append(NAME).append(" { ");
            for (int index = 0; index < fields.size(); index++) {
                if (index > 0) {
                    builder.append(", ");
                }
                fields.get(index).toFormattedString(builder, options);
            }
            builder.append(", ");
            matchingEngine.toFormattedString(builder, options);
            builder.append(" }");
            return;
        }

        builder.append(options.prefix()).append(NAME).append(System.lineSeparator());
        PrintOptions nested = options.nested();
        for (Field field : fields) {
            builder.append(nested.prefix());
            field.toFormattedString(builder, nested);
            builder.append(System.lineSeparator());
        }
        matchingEngine.toFormattedString(builder, nested);
    }

    @Override
    public String toString() {
        return toFormattedString(PrintOptions.DEFAULT);
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (!(other instanceof MassCancelResponse message)) {
            return false;
        }
        return fields.equals(message.fields) && matchingEngine.equals(message.matchingEngine);
    }

    @Override
    public int hashCode() {
        return Objects.hash(fields, matchingEngine);
    }
}
