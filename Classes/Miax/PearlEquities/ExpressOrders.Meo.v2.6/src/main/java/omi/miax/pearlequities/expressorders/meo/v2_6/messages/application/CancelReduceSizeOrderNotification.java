    @Override
    public boolean parseFrom(byte[] data, int offset) {
        return parseFrom(data, offset, data.length);
    }

    @Override
    public boolean parseFrom(byte[] data, int offset, int end) {
        clear();
        this.decoded = read(data, offset, end);

        int stop = Math.max(0, Math.min(data.length, offset + BYTE_LENGTH));
        this.buffer = Arrays.copyOfRange(data, Math.min(Math.max(offset, 0), stop), stop);
        return decoded;
    }

    private boolean read(byte[] data, int offset, int end) {
        if (offset < 0 || end > data.length || end - offset < BYTE_LENGTH) {
            return false;
        }

        int cursor = offset;
        if (!matchingEngineTime.parse(data, cursor)) {
            return false;
        }
        cursor += MatchingEngineTimeField.BYTE_LENGTH;
        if (!mpid.parse(data, cursor)) {
            return false;
        }
        cursor += MpidField.BYTE_LENGTH;
        if (!clientOrderId.parse(data, cursor)) {
            return false;
        }
        cursor += ClientOrderIdField.BYTE_LENGTH;
        if (!symbolId.parse(data, cursor)) {
            return false;
        }
        cursor += SymbolIdField.BYTE_LENGTH;
        if (!orderId.parse(data, cursor)) {
            return false;
        }
        cursor += OrderIdField.BYTE_LENGTH;
        if (!leavesQty.parse(data, cursor)) {
            return false;
        }
        cursor += LeavesQtyField.BYTE_LENGTH;
        if (!cancelReason.parse(data, cursor)) {
            return false;
        }
        cursor += CancelReasonField.BYTE_LENGTH;
        if (!lastPrice.parse(data, cursor)) {
            return false;
        }
        cursor += LastPriceField.BYTE_LENGTH;
        if (!lastSize.parse(data, cursor)) {
            return false;
        }
        cursor += LastSizeField.BYTE_LENGTH;
        if (!pendingCancelStatus.parse(data, cursor)) {
            return false;
        }
        cursor += PendingCancelStatusField.BYTE_LENGTH;
        if (!pendingRejectReason.parse(data, cursor)) {
            return false;
        }
        cursor += PendingRejectReasonField.BYTE_LENGTH;

        return true;
    }

    @Override
    public int encode(byte[] data, int offset) {
        Objects.checkFromIndexSize(offset, BYTE_LENGTH, data.length);
        int cursor = offset;
        cursor = matchingEngineTime.encode(data, cursor);
        cursor = mpid.encode(data, cursor);
        cursor = clientOrderId.encode(data, cursor);
        cursor = symbolId.encode(data, cursor);
        cursor = orderId.encode(data, cursor);
        cursor = leavesQty.encode(data, cursor);
        cursor = cancelReason.encode(data, cursor);
        cursor = lastPrice.encode(data, cursor);
        cursor = lastSize.encode(data, cursor);
        cursor = pendingCancelStatus.encode(data, cursor);
        cursor = pendingRejectReason.encode(data, cursor);
        if (buffer != null && buffer.length >= 71) {
            System.arraycopy(buffer, 63, data, cursor, 8); // padding
        } else {
            Arrays.fill(data, cursor, cursor + 8, (byte) 0); // padding
        }
        cursor += 8;
        return cursor;
    }

    @Override
    public byte[] toBytes() {
        byte[] data = new byte[BYTE_LENGTH];
        encode(data, 0);
        return data;
    }

