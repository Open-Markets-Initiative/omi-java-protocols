    private final List<Field> fields = List.of(matchingEngineTime, mpid, clientOrderId, symbolId, orderId, leavesQty, cancelReason, lastPrice, lastSize, pendingCancelStatus, pendingRejectReason);

    private byte[] buffer;

    private boolean decoded;

